/// 解析自定义词库 JSON：[["词", "同义词1", ...], ...]
pub fn parse_custom_dict(content: &str) -> Result<Vec<Vec<String>>, String> {
    let parsed: Vec<Vec<String>> =
        serde_json::from_str(content).map_err(|e| format!("词库 JSON 解析失败：{e}"))?;
    Ok(parsed
        .into_iter()
        .map(|mut g| {
            g.retain(|w| !w.trim().is_empty());
            g
        })
        .filter(|g| g.len() >= 2)
        .collect())
}

/// 同义词替换：按替换比例（0.0-1.0）将文本中的词替换为组内同义表达
pub fn replace_synonyms(text: &str, ratio: f64, seed: u64, custom: &[Vec<String>]) -> String {
    let mut rng = StdRng::seed_from_u64(seed);
    let mut result = text.to_string();

    let builtin: Vec<Vec<String>> = BUILTIN_GROUPS
        .iter()
        .map(|g| g.iter().map(|s| s.to_string()).collect())
        .collect();
    let all_groups: Vec<&Vec<String>> = builtin.iter().chain(custom.iter()).collect();

    for group in all_groups {
        // 按比例决定本组是否参与替换
        if rng.gen::<f64>() > ratio {
            continue;
        }
        let from = &group[rng.gen_range(0..group.len())];
        let candidates: Vec<&String> = group.iter().filter(|w| *w != from).collect();
        if let Some(to) = candidates.get(rng.gen_range(0..candidates.len())) {
            result = result.replace(from.as_str(), to.as_str());
        }
    }
    result
}

/// 词库统计
pub fn dict_stats(custom: &[Vec<String>]) -> (usize, usize) {
    (BUILTIN_GROUPS.len(), custom.len())
}
